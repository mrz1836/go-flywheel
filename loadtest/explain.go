// ErrClaimSQLUnrecognized reports that the statement the PostgreSQL driver
// emitted does not carry the class predicate this file knows how to rewrite.
//
// It is a hard error rather than a skipped cell on purpose. The whole point of
// capturing the driver's own SQL is that the published plans describe the query
// the runtime actually runs; if the driver's spelling changes underneath, the
// alternative to failing here is silently explaining P0 twice and labelling one
// of them P1.
var ErrClaimSQLUnrecognized = errors.New("captured claim SQL does not carry the expected class predicate")

// claimIndexName is the index the claim is supposed to use. Every variant is
// installed under this one name so the plan output is directly comparable across
// them — a plan that names a different index would not be.
const claimIndexName = "jobs_ready"

// claimStatePredicate is the partial-index predicate the shipped jobs_ready
// carries. The hand-written variants below splice it rather than restating the
// state list, and TestExplainVariantsSharePartialPredicate asserts the shipped
// DDL still contains it — so a change to the runtime's claimable states cannot
// leave the candidate indexes describing a different set of rows than the
// control does.
const claimStatePredicate = `WHERE state IN ('available', 'retryable', 'scheduled')`

// deletedPredicate narrows a candidate index to the rows the claim can actually
// take. The claim filters deleted_at IS NULL (driver_postgres.go) but the
// shipped index predicate does not, so every candidate tuple needs a heap visit
// to answer it.
const deletedPredicate = ` AND deleted_at IS NULL`

// Predicate spellings under test.
const (
	// predicateEmitted is the class clause exactly as the PostgreSQL driver
	// writes it today: an OR on the index's second column.
	predicateEmitted = "P0"
	// predicateInList is the spelling the SQLite driver already uses
	// (driver_sqlite.go). Whether PostgreSQL 17's btree ScalarArrayOp execution
	// preserves index ordering through it is the open question this matrix
	// exists to answer.
	predicateInList = "P1"
)

// explainSeedClasses is how many distinct executor_class values the seed spreads
// rows across: the routed class, the empty wildcard, and two foreign classes. A
// routed claim therefore matches half the table, which is what makes "the class
// filter's heap visits" a real cost rather than a rounding error — a seed in
// which every row matched would flatter any variant that drops the column from
// the key.
const explainSeedClasses = 4

// defaultExplainQueues and defaultExplainLimit are the matrix's shape defaults.
// The limit is the runner's per-poll batch at the published baseline's
// concurrency (Workers: 8), which is what makes "a Sort over more than LIMIT
// rows" the failure signature it is.
const (
	defaultExplainQueues = 3
	defaultExplainLimit  = 8
)

// ExplainConfig declares one characterization run: what to seed, and what shape
// of claim to explain against it.
//
// The zero value is not runnable — DSN and Jobs are required. Everything else
// defaults through validate.
type ExplainConfig struct {
	// DSN is the PostgreSQL target. Required. It never reaches the report: see
	// redactDSN.
	DSN string
	// Jobs is how many claimable rows to seed. Required, positive.
	Jobs int
	// Queues is how many distinct queues the rows are spread across. The
	// conditions then claim from one of them or from all of them, which is the
	// `queue IN (...)` cardinality the matrix varies.
	Queues int
	// Seed makes the seeded workload reproducible; it is the same seed the
	// scenario harness takes, and the rows are generated by the same generator.
	Seed int64
	// ExecutorClass is the class a routed claim asks for.
	ExecutorClass string
	// Limit is the claim's batch size — the runner's Concurrency.
	Limit int
	// Lease is the lease duration stamped by the claim. It changes nothing about
	// the plan; it exists so the captured statement is the one a configured
	// runner would emit.
	Lease time.Duration
}

// validate returns a normalized copy of cfg, or an error naming the field at
// fault. It copies rather than mutating for the same reason Config.validate
// does: a caller's config is never silently rewritten.
func (cfg ExplainConfig) validate() (ExplainConfig, error) {
	if cfg.DSN == "" {
		return ExplainConfig{}, fmt.Errorf("loadtest: %w", ErrNoDSN)
	}
	if cfg.Jobs <= 0 {
		return ExplainConfig{}, fmt.Errorf("loadtest: Jobs must be positive, got %d: %w", cfg.Jobs, ErrInvalidConfig)
	}
	if cfg.Queues < 0 {
		return ExplainConfig{}, fmt.Errorf("loadtest: Queues must not be negative, got %d: %w", cfg.Queues, ErrInvalidConfig)
	}
	if cfg.Queues == 0 {
		cfg.Queues = defaultExplainQueues
	}
	if cfg.Limit < 0 {
		return ExplainConfig{}, fmt.Errorf("loadtest: Limit must not be negative, got %d: %w", cfg.Limit, ErrInvalidConfig)
	}
	if cfg.Limit == 0 {
		cfg.Limit = defaultExplainLimit
	}
	if cfg.Lease <= 0 {
		cfg.Lease = time.Minute
	}
	if cfg.ExecutorClass == "" {
		cfg.ExecutorClass = defaultExecutorClass
	}
	return cfg, nil
}

// explainCondition is one runtime claim shape: which queues it names and whether
// it routes by class. The set of them is the matrix's rows.
type explainCondition struct {
	// Name is the condition label carried into the report.
	Name string
	// Queues is how many of the seeded queues the claim names.
	Queues int
	// ClaimAny mirrors the runner's ClaimAnyClass: it drops the class predicate
	// entirely, which is the second of the two ways the claim misses jobs_ready.
	ClaimAny bool
	// Idle names a queue with no ready rows instead of a seeded one.
	Idle bool
	// Desc is the human-readable shape, for the report header.
	Desc string
}

// idleQueue is a queue name the seed never writes to.
//
// It is how the matrix measures an empty poll, which is not an edge case: a
// runner polls every few milliseconds whether or not there is work, so on any
// quiet queue the overwhelming majority of claims a deployment ever issues
// return nothing. An index that answers a hit quickly and a miss slowly would be
// a worse deployment than the one it replaced.
const idleQueue = "q-idle"

// explainConditions returns the matrix's claim shapes.
//
// A through D are the four shapes the plan of record names: the two queue
// cardinalities crossed with the two routing modes. E and F are additions —
// the same two routing modes against a queue with nothing ready — because a
// candidate index can fix every one of A through D and still ruin the case a
// deployment spends most of its wall clock in.
func explainConditions() []explainCondition {
	return []explainCondition{
		{Name: "A", Queues: 1, ClaimAny: false, Desc: "1 queue,  routed by executor_class"},
		{Name: "B", Queues: 3, ClaimAny: false, Desc: "3 queues, routed by executor_class"},
		{Name: "C", Queues: 1, ClaimAny: true, Desc: "1 queue,  ClaimAnyClass (no class predicate)"},
		{Name: "D", Queues: 3, ClaimAny: true, Desc: "3 queues, ClaimAnyClass (no class predicate)"},
		{Name: "E", Queues: 1, ClaimAny: false, Idle: true, Desc: "idle queue, routed — the empty poll"},
		{Name: "F", Queues: 1, ClaimAny: true, Idle: true, Desc: "idle queue, ClaimAnyClass — the empty poll"},
	}
}

// explainVariant is one jobs_ready definition under test.
type explainVariant struct {
	// Name is the variant label carried into the report.
	Name string
	// Desc says what the definition is and why it is a candidate.
	Desc string
	// DDL creates the index. An empty DDL means the variant is "index absent",
	// which reproduces the published baseline's index-absent row.
	DDL string
	// Only, when non-empty, restricts the variant to that one condition. It
	// exists for the INCLUDE variant, which is a question about one shape rather
	// than a candidate for the whole matrix.
	Only string
}

// variantIndexDDL renders a candidate jobs_ready definition.
//
// Every candidate carries the shipped partial predicate plus deleted_at IS NULL,
// so the only thing that varies between them is the key — which is what makes a
// delta between two variants attributable to the column order rather than to the
// rows the index covers.
func variantIndexDDL(columns, include string) string {
	ddl := "CREATE INDEX IF NOT EXISTS " + claimIndexName + " ON jobs (" + columns + ")"
	if include != "" {
		ddl += " INCLUDE (" + include + ")"
	}
	return ddl + " " + claimStatePredicate + deletedPredicate
}

// explainVariants returns the index definitions under test, control first.
//
// V0 is pulled from the runtime's own IndexSet rather than re-typed. That is the
// same rule the scenario harness follows for its index conditions, and for the
// same reason: a control the harness spells itself is a control that drifts from
// the runtime silently, and then the published plans describe an index nobody
// ships.
func explainVariants() ([]explainVariant, error) {
	shipped, err := shippedClaimIndexDDL()
	if err != nil {
		return nil, err
	}
	return []explainVariant{
		{
			Name: "V-", Desc: "absent — reproduces the baseline's index-absent row",
			DDL: "",
		},
		{
			Name: "V0", Desc: "as shipped, from flywheel.IndexSet(\"postgres\")",
			DDL: shipped,
		},
		{
			Name: "V1", Desc: "V0 + deleted_at IS NULL in the predicate",
			// Derived from the shipped DDL by appending the predicate, so V1 is
			// provably V0 plus one clause rather than a retyped approximation of it.
			DDL: shipped + deletedPredicate,
		},
		{
			Name: "V2", Desc: "ordering columns first: (priority, scheduled_at, queue, executor_class)",
			DDL: variantIndexDDL("priority, scheduled_at, queue, executor_class", ""),
		},
		{
			Name: "V3", Desc: "class dropped from the key: (queue, priority, scheduled_at)",
			DDL: variantIndexDDL("queue, priority, scheduled_at", ""),
		},
		{
			Name: "V4", Desc: "V1 + INCLUDE (id), measured under condition A only",
			DDL:  variantIndexDDL("queue, executor_class, priority, scheduled_at", "id"),
			Only: "A",
		},
	}, nil
}

// shippedClaimIndexDDL finds the claim index in the runtime's own index set.
func shippedClaimIndexDDL() (string, error) {
	set, err := flywheel.IndexSet("postgres")
	if err != nil {
		return "", fmt.Errorf("loadtest: index set: %w", err)
	}
	for _, idx := range set {
		if idx.Name == claimIndexName {
			return idx.DDL, nil
		}
	}
	return "", fmt.Errorf("loadtest: %w: the runtime's index set has no %s", ErrInvalidConfig, claimIndexName)
}

// PlanSummary is the handful of numbers a reader compares cells by, lifted out
// of the plan text.
//
// The full plan is kept alongside it — this is a reading aid, not a replacement.
// A summary that disagreed with the text it summarizes would be worse than no
// summary at all, so every field here is parsed from the text rather than
// inferred from the query.
type PlanSummary struct {
	// Scan is the scan node the claim's inner select drives, verbatim.
	Scan string `json:"scan"`
	// ScanKind is that node's type: "Seq Scan", "Index Scan", "Bitmap Heap
	// Scan", and so on.
	ScanKind string `json:"scan_kind"`
	// IndexUsed names the index, when the scan is an index scan.
	IndexUsed string `json:"index_used,omitempty"`
	// ScanRows is how many rows the scan actually returned. Against a LIMIT of
	// 8, a scan returning six figures is the whole finding.
	ScanRows int64 `json:"scan_rows"`
	// Sorted reports whether a Sort node sits above the scan. A Sort over more
	// than LIMIT rows is the failure signature.
	Sorted bool `json:"sorted"`
	// SortMethod is the Sort node's method line, which is where an external
	// merge and its spill size appear.
	SortMethod string `json:"sort_method,omitempty"`
	// RowsRemoved is how many rows the scan's filter discarded — the cost of
	// applying a predicate at the heap instead of in the index.
	RowsRemoved int64 `json:"rows_removed_by_filter"`
	// SharedHit and SharedRead are the statement's buffer totals.
	SharedHit  int64 `json:"shared_hit"`
	SharedRead int64 `json:"shared_read"`
	// PlanningMS and ExecutionMS are the reported times.
	PlanningMS  float64 `json:"planning_ms"`
	ExecutionMS float64 `json:"execution_ms"`
}

// ExplainCell is one measured square of the matrix.
type ExplainCell struct {
	Condition string      `json:"condition"`
	Predicate string      `json:"predicate"`
	Variant   string      `json:"variant"`
	Summary   PlanSummary `json:"summary"`
	Plan      []string    `json:"plan"`
}

// Key is the cell's stable label, "A/P0/V1".
func (c ExplainCell) Key() string { return c.Condition + "/" + c.Predicate + "/" + c.Variant }

// ExplainStatement is one captured claim, kept once rather than per cell: every
// variant explains the same bytes, so repeating the statement in every cell
// would triple the artifact for no information.
type ExplainStatement struct {
	Condition string `json:"condition"`
	Predicate string `json:"predicate"`
	SQL       string `json:"sql"`
}

